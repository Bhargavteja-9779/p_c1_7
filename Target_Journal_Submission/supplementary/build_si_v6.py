"""Generate the v6 Supporting Information (ADCC-CP) markdown from the machine-readable
results, so every SI number traces to code. Writes supplementary/supplementary_information.md."""
import json, statistics
from pathlib import Path
HERE = Path(__file__).resolve().parent
RES = HERE.parent / "code" / "results"
st = json.load(open(RES / "adcc_stats.json"))
NAMES = {"split": "Split CP", "normalized": "Normalized CP", "mondrian": "Mondrian-AD CP",
         "weighted_kmm": "KMM-weighted CP", "weighted_ad": "ADR-CP (1-D AD weights)",
         "mwcp": "MW-CP", "adcc": "ADCC-CP", "adcc_grp": "ADCC indicator class",
         "adcc_pl": "ADCC piecewise-linear", "adcc_norm": "ADCC normalized score", "adcc_2d": "ADCC-CP-2D (multi-coordinate)"}
order = ["split", "normalized", "mondrian", "weighted_kmm", "weighted_ad", "mwcp",
         "adcc", "adcc_2d", "adcc_grp", "adcc_pl", "adcc_norm"]


def row(m):
    p = st["pooled"][m]
    return f"| {NAMES[m]} | {p['marginal_coverage']:.3f} | {p['s0_coverage']:.3f} | {p['tail10_coverage']:.3f} | {p['worst_stratum_coverage']:.3f} | {p['mean_abs_stratum_gap']:.3f} | {p['mean_width']:.2f} | {100*p['saturated_fraction']:.0f}% |"


L = []
L.append("# Supporting Information")
L.append("")
L.append("**Applicability-Domain Conditional Conformal Prediction: Distribution-Free Coverage over Chemical-Space Shifts without Density-Ratio Estimation**")
L.append("")
L.append("All numbers are generated by the released code from the machine-readable files in `code/results/`. "
         "Section references are to the main text.")
L.append("")

L.append("## S-adcc-pre. Function-class pre-registration")
L.append("")
L.append("The ADCC-CP function class was selected on the four MoleculeNet scaffold datasets only "
         "(LightGBM, seeds 0–4, α=0.10), with the thirteen-target ChEMBL temporal panel held out. "
         "The continuous linear spline was locked as primary before any panel run. Full record and "
         "development-set numbers: `supplementary/adcc_preregistration.md` and `code/results/dev_adcc_rows.jsonl`.")
L.append("")

L.append("## S-adcc-panel. Pooled temporal-panel results (all methods)")
L.append("")
L.append("Pooled over thirteen ChEMBL targets × three windows × two base models × three seeds "
         f"({st['n_runs']} runs per method). S0 = most out-of-domain stratum; novel decile = most "
         "dissimilar 10 % of test compounds; gap = mean absolute deviation from the 0.90 target across strata.")
L.append("")
L.append("| Method | Marginal | S0 | Novel decile | Worst stratum | Mean |gap| | Width | Saturated |")
L.append("|---|---|---|---|---|---|---|---|")
for m in order:
    L.append(row(m))
L.append("")

L.append("## S-adcc-stats. Target-level paired tests (primary and secondary endpoints)")
L.append("")
L.append("Target-level (n=13) paired Wilcoxon signed-rank tests (Holm-corrected across the six baselines) "
         "and 95 % cluster-bootstrap CIs of ADCC-CP minus each baseline.")
for metric, title in [("worst_stratum_coverage", "Worst-stratum coverage (primary)"),
                      ("s0_coverage", "Most-out-of-domain-stratum (S0) coverage"),
                      ("tail10_coverage", "Most-novel-decile coverage"),
                      ("mean_abs_stratum_gap", "Mean absolute stratum gap (lower = better)")]:
    L.append("")
    L.append(f"**{title}.**")
    L.append("")
    L.append("| Baseline | ADCC − baseline | 95% CI | Targets ADCC better | Holm p |")
    L.append("|---|---|---|---|---|")
    for r in st["target_level"][metric]:
        L.append(f"| {NAMES[r['baseline']]} | {r['mean_diff']:+.3f} | [{r['ci_lo']:+.3f}, {r['ci_hi']:+.3f}] | {r['n_better']}/{r['n']} | {r['p_holm']:.2g} |")
L.append("")

if "validity" in st:
    L.append("## S-adcc-validity. Validity controls (exchangeable and known-shift)")
    L.append("")
    L.append("Mean over 10 seeds × 8 datasets (4 MoleculeNet + 4 ChEMBL), LightGBM, α=0.10. "
             "`random` = exchangeable i.i.d. split (no shift). `adtilt_pl` = controlled shift whose known "
             "density ratio is piecewise-linear in a(x) (inside ADCC-CP's class; Theorem 1 applies exactly). "
             "`adtilt_exp` = known ratio exponential in a(x) (outside the class; tests Proposition 2).")
    L.append("")
    L.append("| Setting | Method | Marginal | Worst stratum | S0 | Novel decile | Width |")
    L.append("|---|---|---|---|---|---|---|")
    for r in st["validity"]:
        L.append(f"| {r['setting']} | {NAMES.get(r['method'], r['method'])} | {r['marginal_coverage']:.3f} | "
                 f"{r['worst_stratum_coverage']:.3f} | {r['s0_coverage']:.3f} | {r['tail10_coverage']:.3f} | {r['mean_width']:.2f} |")
    L.append("")

# misspec diagnostic
dpath = RES / "misspec_diag.jsonl"
if dpath.exists():
    rows = [json.loads(l) for l in open(dpath)]
    tgs = sorted(set(r["target"] for r in rows))
    L.append("## S-adcc-diag. Label-free misspecification diagnostic")
    L.append("")
    L.append("Per target (mean over three windows × three seeds): $\\delta_{\\mathcal F}$ = total-variation "
             "distance from the estimated covariate-shift ratio to its best applicability-domain-aligned "
             "approximation (Proposition 2 bound on ADCC-CP's coverage shortfall); $\\delta_0$ = distance "
             "to 'no shift' (the corresponding bound for split conformal). $\\delta_{\\mathcal F}<\\delta_0$ "
             "means AD-aligned correction helps; the gap is the certified improvement. No labels are used.")
    L.append("")
    L.append("| Target | $\\delta_{\\mathcal F}$ | $\\delta_0$ | $\\delta_0-\\delta_{\\mathcal F}$ |")
    L.append("|---|---|---|---|")
    for t in tgs:
        rs = [r for r in rows if r["target"] == t]
        dF = statistics.mean(r["delta_F"] for r in rs); d0 = statistics.mean(r["delta_0"] for r in rs)
        L.append(f"| {t} | {dF:.3f} | {d0:.3f} | {d0-dF:+.3f} |")
    allF = statistics.mean(r["delta_F"] for r in rows); all0 = statistics.mean(r["delta_0"] for r in rows)
    L.append(f"| **mean** | **{allF:.3f}** | **{all0:.3f}** | **{all0-allF:+.3f}** |")
    L.append("")

# by window / by model
L.append("## S-adcc-window / S-adcc-model. Robustness to shift severity and base model")
L.append("")
L.append("S0 and worst-stratum coverage by temporal window (w40/w30/w20 = test latest 40/30/20 %) and by base model.")
for key, title in [("by_window", "By window"), ("by_model", "By base model")]:
    L.append("")
    L.append(f"**{title}.**")
    L.append("")
    k0 = "window" if key == "by_window" else "model"
    L.append(f"| {k0} | method | S0 | worst stratum | width |")
    L.append("|---|---|---|---|---|")
    for r in st[key]:
        L.append(f"| {r[k0]} | {NAMES.get(r['method'], r['method'])} | {r['s0_coverage']:.3f} | {r['worst_stratum_coverage']:.3f} | {r['mean_width']:.2f} |")
L.append("")

L.append("## S-adcc-ablation. Function-class ablation")
L.append("")
L.append("The function class is the only design choice. On the held-out panel, the indicator class "
         "reproduces Mondrian; the spline (primary) and piecewise-linear classes give the best "
         "novel-compound coverage and calibration; the normalized-score spline trades width/saturation "
         "for marginal gains (table S-adcc-panel). This confirms the class, not incidental tuning, drives the result.")
L.append("")

L.append("## S-adcc-leak. Data-leakage audit")
L.append("")
L.append("For every target the audit asserts chronological monotonicity (max train/calib year ≤ min test "
         "year up to boundary ties), InChIKey de-duplication, applicability-domain scores computed to the "
         "training set only, and that no labels enter featurization, AD scores or the (baseline) weight "
         "estimators. See `code/experiments/leakage_audit.py` and `code/results/leakage_audit_panel.json`.")
L.append("")

L.append("## S-prior. Prior estimated-weight benchmark")
L.append("")
L.append("The estimated-weight methods ADR-CP and MW-CP, and the earlier multi-target benchmark that "
         "motivated this work (including the CoDrug-/KMM-style weightings and the cross-target diagnostic "
         "analysis), are retained in the released code and summarized in the main text. ADCC-CP matches or "
         "exceeds their decision-relevant coverage while removing the density-ratio estimate and adding a "
         "finite-sample guarantee.")
L.append("")

(HERE / "supplementary_information.md").write_text("\n".join(L) + "\n")
print(f"wrote supplementary_information.md ({len(L)} lines)")
